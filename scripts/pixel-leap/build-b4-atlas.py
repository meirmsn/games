"""Builds Pixel Leap's batch-4 sheets from the Kenney packs in the private assets repo:
pixel-leap/img/scribble.png + pixel-leap/scribble-atlas.js (Scribble Platformer) and
pixel-leap/img/jumper.png + pixel-leap/jumper-atlas.js (Jumper Pack). Only the sprites the game
draws are copied. Usage:
  python3 scripts/pixel-leap/build-b4-atlas.py "<games-private>/kenney-all-in-1/2D assets"
"""
import json
import os
import sys

from PIL import Image

src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'pixel-leap')

# Scribble: its Retina tiles are 128 px; the game draws 70 px per tile.
SCRIBBLE = ['tile', 'tile_grass', 'tile_top', 'tile_bridge', 'tile_spikes', 'tile_coin', 'tile_heart', 'tile_door',
            'tile_bush', 'tile_bushHalf', 'tile_tree', 'item_pencil', 'background_cloudA', 'background_cloudB',
            'background_tree']
# Jumper: sprites at their own sizes, scaled down (ledges to 40 px tall, the rest by 0.6).
JUMPER = {
    'Environment': ['ground_grass', 'ground_grass_small', 'ground_grass_broken', 'ground_grass_small_broken',
                    'ground_stone', 'ground_stone_small'],
    'Items': ['spring', 'spring_out', 'powerup_wings', 'wing_left', 'wing_right', 'gold_1', 'gold_2', 'gold_3',
              'gold_4', 'portal_yellow'],
    'Enemies': ['wingMan1', 'wingMan2', 'wingMan3', 'wingMan4', 'spikeMan_stand', 'spikeMan_walk1', 'spikeMan_walk2'],
}


def pack(items, width):
    """Shelf-packs (name, image) pairs into one sheet; returns the sheet and name -> [x, y, w, h]."""
    x = y = shelf = 0
    pos = {}
    for name, im in items:
        w, h = im.size
        if x + w > width:
            x, y, shelf = 0, y + shelf + 2, 0
        pos[name] = [x, y, w, h]
        x += w + 2
        shelf = max(shelf, h)
    sheet = Image.new('RGBA', (width, y + shelf), (0, 0, 0, 0))
    for name, im in items:
        sheet.paste(im, tuple(pos[name][:2]))
    return sheet, pos


def write(name, var, sheet, pos):
    sheet.save(os.path.join(out, 'img', name + '.png'), optimize=True)
    with open(os.path.join(out, name + '-atlas.js'), 'w') as f:
        f.write("// Generated by scripts/pixel-leap/build-b4-atlas.py from the Kenney pack's PNGs: "
                'name -> [x, y, w, h].\n')
        f.write(f'export const {var} = {json.dumps(pos, separators=(",", ":"))};\n')


items = []
for n in SCRIBBLE:
    im = Image.open(os.path.join(src, 'Scribble Platformer', 'PNG', 'Retina', n + '.png')).convert('RGBA')
    w, h = im.size
    items.append((n, im.resize((round(w * 70 / 128), round(h * 70 / 128)), Image.LANCZOS)))
write('scribble', 'SCRIBBLE', *pack(items, 512))

items = []
for folder, names in JUMPER.items():
    for n in names:
        im = Image.open(os.path.join(src, 'Jumper Pack', 'PNG', folder, n + '.png')).convert('RGBA')
        w, h = im.size
        s = 40 / h if n.startswith('ground_') else 0.6
        items.append((n, im.resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS)))
write('jumper', 'JUMPER', *pack(items, 512))
