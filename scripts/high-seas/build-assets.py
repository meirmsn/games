#!/usr/bin/env python3
"""Build High Seas' sprite atlas and sounds from the Kenney packs in meirmsn/games-private.

Run once when the art or sounds change, with the asset repo checked out:
    python3 scripts/high-seas/build-assets.py /path/to/games-private
Needs Pillow and ffmpeg. Writes high-seas/img/atlas.png, high-seas/atlas.js and high-seas/sounds/*.mp3.
Every sprite is cropped to its pixels; its anchor (ax, ay) is where it touches the water or the
ground, as a fraction of the cropped size, so the game can stand it on its tile.
"""
import json
import os
import subprocess
import sys

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
OUT = os.path.join(ROOT, 'high-seas')

if len(sys.argv) != 2:
    sys.exit('usage: build-assets.py /path/to/games-private')
K = os.path.join(sys.argv[1], 'kenney-all-in-1')
NATURE = os.path.join(K, '2D assets', 'Isometric Nature', 'PNG', 'naturePack_%s_%d.png')
CRAFT = os.path.join(K, '2D assets', 'Isometric Watercraft', 'PNG', 'watercraftPack_%03d_%d.png')
AUDIO = os.path.join(K, 'Audio')

# name: (path, scale, anchor y as a fraction of the cropped height: where it meets the ground)
sprites = {}
for n in ['167', '168', '169', '073', '081', '084']:
    sprites['tree' + n] = (NATURE % (n, 0), 0.5, 0.93)
for n in ['035', '036', '037', '025', '019', '021', '022']:
    sprites['rock' + n] = (NATURE % (n, 0), 0.5, 0.8)
for k in range(8):
    sprites['galleon%d' % k] = (CRAFT % (7, k), 0.55, 0.78)
# Traffic: boats that sail between the ports on their own, in all eight headings.
for boat, scale in [(23, 0.42), (19, 0.42), (29, 0.4), (6, 0.5)]:
    for k in range(8):
        sprites['traffic%d_%d' % (boat, k)] = (CRAFT % (boat, k), scale, 0.72)
# Moored boats: houseboats, a rowboat, a tug and a buoy, in two headings each.
for boat, frames in [(25, [0, 2]), (26, [0, 2]), (28, [0, 2]), (23, [0, 2]), (27, [0])]:
    for k in frames:
        sprites['boat%d_%d' % (boat, k)] = (CRAFT % (boat, k), 0.5 if boat != 28 else 0.45, 0.72)

images = {}
for name, (path, scale, ay) in sprites.items():
    im = Image.open(path).convert('RGBA')
    im = im.crop(im.getbbox())
    w, h = max(1, round(im.width * scale)), max(1, round(im.height * scale))
    images[name] = (im.resize((w, h), Image.LANCZOS), ay)

# Shelf packing, tallest first.
order = sorted(images, key=lambda n: -images[n][0].height)
W = 1024
x = y = shelf = 0
placed = {}
for name in order:
    im = images[name][0]
    if x + im.width + 2 > W:
        x, y, shelf = 0, y + shelf + 2, 0
    placed[name] = (x, y)
    x += im.width + 2
    shelf = max(shelf, im.height)
H = y + shelf
atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
table = {}
for name, (px, py) in placed.items():
    im, ay = images[name]
    atlas.paste(im, (px, py))
    table[name] = [px, py, im.width, im.height, ay]
os.makedirs(os.path.join(OUT, 'img'), exist_ok=True)
# Flat art keeps its look in a 256-colour palette, at a third of the size.
atlas.quantize(256, method=Image.Quantize.FASTOCTREE).save(os.path.join(OUT, 'img', 'atlas.png'), optimize=True)
with open(os.path.join(OUT, 'atlas.js'), 'w') as f:
    f.write('// Generated by scripts/high-seas/build-assets.py: name -> [x, y, w, h, anchorY].\n')
    f.write('// Art by Kenney (CC0): Isometric Nature and Isometric Watercraft.\n')
    f.write('export const ATLAS = ' + json.dumps(table, separators=(',', ':')) + ';\n')
print('atlas %dx%d, %d sprites' % (W, H, len(table)))

# Sounds: MP3, because Safari doesn't play OGG.
os.makedirs(os.path.join(OUT, 'sounds'), exist_ok=True)


def mp3(dst, args):
    out = os.path.join(OUT, 'sounds', dst + '.mp3')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', *args, '-ac', '1', '-ar', '44100', '-b:a', '64k', out], check=True)


def take(dst, src, extra=None):
    mp3(dst, ['-i', os.path.join(AUDIO, src), *(['-af', extra] if extra else [])])


take('luff', 'RPG Audio/Audio/cloth3.ogg')
take('tack', 'RPG Audio/Audio/cloth1.ogg')
take('gust', 'Foley Sounds/Audio/Woosh/woosh7.ogg', 'volume=0.8')
take('creak', 'RPG Audio/Audio/creak1.ogg')
take('splash', 'Foley Sounds/Audio/Water/sinkWater2.ogg')
take('bump', 'Impact Sounds/Audio/impactWood_heavy_001.ogg')
take('bell', 'Impact Sounds/Audio/impactBell_heavy_000.ogg', 'volume=0.6')
take('coins', 'RPG Audio/Audio/handleCoins.ogg')
take('load', 'Impact Sounds/Audio/impactPlank_medium_000.ogg')
take('buy', 'Music Jingles/Audio (Steeldrum)/jingles-steel_04.ogg')
take('fanfare', 'Music Jingles/Audio (Steeldrum)/jingles-steel_10.ogg')
take('shift', 'Music Jingles/Audio (Pizzicato)/jingles-pizzicato_02.ogg', 'volume=0.7')
# The sea: brown noise, low-passed, swelling like waves; 12 s, faded at both ends to loop without a click.
mp3(
    'sea',
    [
        '-f', 'lavfi', '-i', 'anoisesrc=color=brown:amplitude=0.6:duration=12:seed=7',
        '-af',
        'lowpass=f=700,highpass=f=60,volume=0.9,'
        "volume='0.55+0.45*sin(2*PI*t/6)':eval=frame,"
        'afade=t=in:d=0.05,afade=t=out:st=11.95:d=0.05',
    ],
)
print('sounds written')
